import { test } from 'node:test';
import { strict as assert } from 'node:assert';
import { diffBundleSnapshots } from '../src/analyzers/bundleSizeDiff.js';
import { measureModuleSizes, normalizeModuleId } from '../src/detectors/bundleStats.js';
import { BUNDLE_SNAPSHOT_SCHEMA_VERSION, type BundleSnapshot } from '../src/types/bundleSize.js';

function snap(over: Partial<BundleSnapshot> & { modules?: BundleSnapshot['modules']; js?: number; hbc?: number | null } = {}): BundleSnapshot {
  return {
    schemaVersion: BUNDLE_SNAPSHOT_SCHEMA_VERSION,
    platform: over.platform ?? 'ios',
    commitSha: null,
    toolchain: over.toolchain ?? { metroVersion: '0.83.0', hermesVersion: '0.14.0' },
    totals: { jsBytes: over.js ?? 3000, hbcBytes: over.hbc === undefined ? 1000 : over.hbc, unmappedBytes: 0 },
    modules: over.modules ?? [{ id: 'App.tsx', bytes: 1000 }, { id: 'node_modules/a/index.js', bytes: 2000 }],
  };
}

test('diff - classifies added/removed/grown/shrunk and totals', () => {
  const base = snap();
  const head = snap({
    js: 3500,
    modules: [{ id: 'App.tsx', bytes: 1200 }, { id: 'node_modules/b/index.js', bytes: 2300 }],
  });
  const r = diffBundleSnapshots(base, head);
  assert.equal(r.status, 'ok');
  assert.deepEqual(r.added.map((m) => m.id), ['node_modules/b/index.js']);
  assert.deepEqual(r.removed.map((m) => m.id), ['node_modules/a/index.js']);
  assert.deepEqual(r.grown.map((m) => m.id), ['App.tsx']);
  assert.equal(r.totals?.js.delta, 500);
});

test('diff - budget violations: total, bytecode, per-module growth honoring ignore', () => {
  const head = snap({ js: 5 * 1024, hbc: 3 * 1024, modules: [{ id: 'node_modules/big/x.js', bytes: 4096 }, { id: 'assets/gen.js', bytes: 4096 }] });
  const r = diffBundleSnapshots(snap({ modules: [] }), head, { totalJsKb: 4, totalHbcKb: 2, perModuleGrowthKb: 1, ignore: ['assets/'] });
  assert.equal(r.status, 'over-budget');
  assert.deepEqual(r.violations.map((v) => v.kind).sort(), ['moduleGrowth', 'totalHbc', 'totalJs']);
  assert.equal(r.violations.find((v) => v.kind === 'moduleGrowth')?.module, 'node_modules/big/x.js');
});

test('diff - unlike snapshots are not-comparable, never compared', () => {
  const r = diffBundleSnapshots(snap(), snap({ toolchain: { metroVersion: '0.84.0', hermesVersion: '0.14.0' } }));
  assert.equal(r.status, 'not-comparable');
  assert.match(r.reason ?? '', /Metro/);
  assert.equal(diffBundleSnapshots(snap(), snap({ platform: 'android' })).status, 'not-comparable');
});

test('diff - unknown toolchain compares with a warning; missing bytecode budget is not-checked', () => {
  const r = diffBundleSnapshots(snap(), snap({ hbc: null, toolchain: { metroVersion: null, hermesVersion: null } }), { totalHbcKb: 1 });
  assert.equal(r.status, 'ok');
  assert.equal(r.warnings.length, 2);
  assert.equal(r.notChecked.length, 1);
  assert.equal(r.totals?.hbc, null);
});

test('measureModuleSizes - attributes generated bytes through mappings', () => {
  // line 0: "aaaabb" → cols 0-3 from src0, cols 4-5 from src1
  const map = { version: 3, sources: ['/proj/App.tsx', '/proj/node_modules/x/i.js?foo'], mappings: 'AAAA,ICAA' };
  const r = measureModuleSizes('aaaabb', map, '/proj');
  assert.ok(r);
  assert.deepEqual(r.modules, [{ id: 'App.tsx', bytes: 4 }, { id: 'node_modules/x/i.js', bytes: 2 }]);
  assert.equal(r.jsBytes, 6);
  assert.equal(r.unmappedBytes, 0);
});

test('measureModuleSizes - attributes bytes across index-map sections (Metro JS output)', () => {
  const text = 'abcd\nefgh';
  const map = {
    version: 3,
    sections: [
      { offset: { line: 0, column: 0 }, map: { version: 3, sources: ['/p/a.js'], mappings: 'AAAA' } },
      { offset: { line: 1, column: 0 }, map: { version: 3, sources: ['/p/b.js'], mappings: 'AAAA' } },
    ],
  };
  const r = measureModuleSizes(text, map, '/p');
  assert.ok(r);
  assert.deepEqual(r.modules, [{ id: 'a.js', bytes: 4 }, { id: 'b.js', bytes: 4 }]);
  assert.equal(r.unmappedBytes, 1);
});

test('measureModuleSizes - rejects nested sections and malformed input without throwing', () => {
  assert.equal(measureModuleSizes('x', { version: 3, sections: [{ offset: { line: 0, column: 0 }, map: { sections: [] } }] }, '/p'), null);
  assert.equal(measureModuleSizes('x', { version: 3, sections: 'nope' }, '/p'), null);
  assert.equal(measureModuleSizes('x', { version: 3, sources: ['a'], mappings: 'A!A' }, '/p'), null);
  assert.equal(measureModuleSizes('x', null, '/p'), null);
});

test('measureModuleSizes - ids stay project-relative when the root is a symlink to the map\'s path', async () => {
  const { mkdtempSync, symlinkSync, realpathSync } = await import('node:fs');
  const { tmpdir } = await import('node:os');
  const { join } = await import('node:path');
  const real = realpathSync(mkdtempSync(join(tmpdir(), 'size-real-')));
  const link = `${real}-link`;
  symlinkSync(real, link);
  const map = { version: 3, sources: [`${real}/App.tsx`], mappings: 'AAAA' };
  const r = measureModuleSizes('abc', map, link);
  assert.deepEqual(r?.modules.map((m) => m.id), ['App.tsx']);
});

test('normalizeModuleId - treats Expo-style leading-slash paths as project-relative when they exist under the root', async () => {
  const { mkdtempSync, mkdirSync, writeFileSync, realpathSync } = await import('node:fs');
  const { tmpdir } = await import('node:os');
  const { join } = await import('node:path');
  const root = realpathSync(mkdtempSync(join(tmpdir(), 'size-expo-')));
  mkdirSync(join(root, 'src'));
  writeFileSync(join(root, 'src', 'App.tsx'), '');
  assert.equal(normalizeModuleId('/src/App.tsx', root), 'src/App.tsx');
  assert.equal(normalizeModuleId('/elsewhere/x.js', root), '/elsewhere/x.js');
});

test('readHbcBytecodeVersion - reads the version from a Hermes header and rejects other files', async () => {
  const { mkdtempSync, writeFileSync, mkdirSync } = await import('node:fs');
  const { tmpdir } = await import('node:os');
  const { join } = await import('node:path');
  const { readHbcBytecodeVersion, detectHermesCompilerVersion, detectMetroVersion } = await import('../src/detectors/bundleToolchain.js');
  const dir = mkdtempSync(join(tmpdir(), 'size-hbc-'));
  const header = Buffer.concat([Buffer.from('c61fbc03c103191f', 'hex'), Buffer.from([99, 0, 0, 0])]);
  writeFileSync(join(dir, 'ok.hbc'), header);
  writeFileSync(join(dir, 'js.hbc'), 'not bytecode at all');
  writeFileSync(join(dir, 'short.hbc'), header.subarray(0, 5));
  assert.equal(readHbcBytecodeVersion(join(dir, 'ok.hbc')), 99);
  assert.equal(readHbcBytecodeVersion(join(dir, 'js.hbc')), null);
  assert.equal(readHbcBytecodeVersion(join(dir, 'short.hbc')), null);
  assert.equal(readHbcBytecodeVersion(join(dir, 'missing.hbc')), null);

  assert.equal(detectMetroVersion(dir), null);
  mkdirSync(join(dir, 'node_modules', 'metro'), { recursive: true });
  writeFileSync(join(dir, 'node_modules', 'metro', 'package.json'), JSON.stringify({ version: '0.83.3' }));
  assert.equal(detectMetroVersion(dir), '0.83.3');
  assert.equal(detectHermesCompilerVersion(dir), null);
});
