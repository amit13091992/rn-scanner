import { existsSync, realpathSync } from 'node:fs';
import { join, posix, relative, sep } from 'node:path';
import type { BundleModuleSize } from '../types/bundleSize.js';

export interface ModuleSizeMeasurement {
  readonly modules: readonly BundleModuleSize[];
  readonly jsBytes: number;
  readonly unmappedBytes: number;
}

const B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
const B64_INDEX = new Map([...B64].map((c, i) => [c, i]));

/** Decodes one VLQ segment; returns `null` on any invalid character (runs on untrusted input). */
function decodeSegment(segment: string): number[] | null {
  const out: number[] = [];
  let value = 0;
  let shift = 0;
  for (const ch of segment) {
    const digit = B64_INDEX.get(ch);
    if (digit === undefined) return null;
    value += (digit & 31) * 2 ** shift;
    if (digit & 32) {
      shift += 5;
    } else {
      out.push(value % 2 === 1 ? -Math.floor(value / 2) : Math.floor(value / 2));
      value = 0;
      shift = 0;
    }
  }
  return shift === 0 ? out : null;
}

/** Strips a loader query/hash and makes the path project-relative with POSIX separators. */
export function normalizeModuleId(source: string, projectRoot: string): string {
  const withoutQuery = source.replace(/[?#].*$/, '');
  // A symlinked root (macOS /var → /private/var) makes the map's paths and cwd disagree.
  let realRoot = projectRoot;
  try { realRoot = realpathSync(projectRoot); } catch { /* root may not exist (tests) */ }
  for (const root of [projectRoot, realRoot]) {
    const rel = relative(root, withoutQuery);
    if (rel !== '' && !rel.startsWith('..')) return rel.split(sep).join(posix.sep);
  }
  // Expo/Metro exports root-relative paths with a leading slash ("/src/App.tsx"), not absolute ones.
  if (withoutQuery.startsWith('/') && existsSync(join(projectRoot, withoutQuery))) return withoutQuery.slice(1);
  return withoutQuery.split(sep).join(posix.sep);
}

interface SourceMapPart {
  readonly sources?: unknown;
  readonly mappings?: unknown;
}

/** Attributes one v3 map's segments to `bytesById`, with its output placed at `offset` in the bundle. Returns mapped bytes, or `null` if malformed. */
function attributePart(
  part: SourceMapPart,
  lines: readonly string[],
  offset: { line: number; column: number },
  projectRoot: string,
  bytesById: Map<string, number>,
): number | null {
  if (!Array.isArray(part.sources) || !part.sources.every((s) => typeof s === 'string')) return null;
  if (typeof part.mappings !== 'string') return null;
  const ids = (part.sources as string[]).map((s) => normalizeModuleId(s, projectRoot));
  const mappingLines = part.mappings.split(';');
  let mappedBytes = 0;
  let srcIdx = 0;

  for (let i = 0; i < mappingLines.length; i++) {
    const lineNo = offset.line + i;
    if (lineNo >= lines.length) break;
    const line = lines[lineNo] ?? '';
    const raw = mappingLines[i] ?? '';
    if (raw === '') continue;
    // Only the section's first line starts mid-line; later lines are columned from 0.
    let genCol = i === 0 ? offset.column : 0;
    const segs: { col: number; src: number | null }[] = [];
    for (const text of raw.split(',')) {
      const f = decodeSegment(text);
      if (f === null || f.length === 0) return null;
      genCol += f[0] ?? 0;
      if (f.length >= 4) {
        srcIdx += f[1] ?? 0;
        if (srcIdx < 0 || srcIdx >= ids.length) return null;
        segs.push({ col: genCol, src: srcIdx });
      } else {
        segs.push({ col: genCol, src: null });
      }
    }
    for (let k = 0; k < segs.length; k++) {
      const seg = segs[k];
      if (!seg || seg.src === null) continue;
      const end = segs[k + 1]?.col ?? line.length;
      if (end <= seg.col) continue;
      const bytes = Buffer.byteLength(line.slice(seg.col, end), 'utf8');
      const id = ids[seg.src] as string;
      bytesById.set(id, (bytesById.get(id) ?? 0) + bytes);
      mappedBytes += bytes;
    }
  }
  return mappedBytes;
}

/**
 * Attributes each generated byte of a bundle to the source file whose mapping segment covers it.
 * Uses the bundle text itself for line lengths, so UTF-8 byte counts are exact for the generated
 * code (the attribution to a module is still an estimate). Accepts a plain v3 map or an index map
 * (`sections`, which Metro emits for JS bundles); returns `null` for anything else or malformed.
 */
export function measureModuleSizes(bundleText: string, sourceMap: unknown, projectRoot: string): ModuleSizeMeasurement | null {
  if (typeof sourceMap !== 'object' || sourceMap === null) return null;
  const map = sourceMap as { version?: unknown; sources?: unknown; mappings?: unknown; sections?: unknown };
  if (map.version !== 3) return null;

  const bytesById = new Map<string, number>();
  const lines = bundleText.split('\n');
  let mappedBytes = 0;

  if (map.sections !== undefined) {
    if (!Array.isArray(map.sections)) return null;
    for (const section of map.sections as unknown[]) {
      if (typeof section !== 'object' || section === null) return null;
      const { offset, map: inner } = section as { offset?: { line?: unknown; column?: unknown }; map?: SourceMapPart & { sections?: unknown } };
      if (typeof offset?.line !== 'number' || typeof offset.column !== 'number' || !inner || inner.sections !== undefined) return null;
      const mapped = attributePart(inner, lines, { line: offset.line, column: offset.column }, projectRoot, bytesById);
      if (mapped === null) return null;
      mappedBytes += mapped;
    }
  } else {
    const mapped = attributePart(map, lines, { line: 0, column: 0 }, projectRoot, bytesById);
    if (mapped === null) return null;
    mappedBytes = mapped;
  }

  const jsBytes = Buffer.byteLength(bundleText, 'utf8');
  const modules = [...bytesById].map(([id, bytes]) => ({ id, bytes })).sort((a, b) => a.id.localeCompare(b.id));
  return { modules, jsBytes, unmappedBytes: jsBytes - mappedBytes };
}
