export const BUNDLE_SNAPSHOT_SCHEMA_VERSION = 1 as const;

export type BundlePlatform = 'ios' | 'android';

export interface BundleModuleSize {
  /** Project-root-relative POSIX path of the source file the bytes were attributed to. */
  readonly id: string;
  readonly bytes: number;
}

export interface BundleSnapshot {
  readonly schemaVersion: typeof BUNDLE_SNAPSHOT_SCHEMA_VERSION;
  readonly platform: BundlePlatform;
  readonly commitSha: string | null;
  readonly toolchain: {
    /** `null` = could not be determined (never a guess). */
    readonly metroVersion: string | null;
    readonly hermesVersion: string | null;
  };
  readonly totals: {
    readonly jsBytes: number;
    /** `null` when no Hermes bytecode file was measured. */
    readonly hbcBytes: number | null;
    /** Generated bytes the source map could not attribute to any module (runtime glue, newlines). */
    readonly unmappedBytes: number;
  };
  /** Sorted by id. */
  readonly modules: readonly BundleModuleSize[];
}

export interface BundleBudget {
  /** Max total JS bundle size of the head snapshot, in KiB (1024 bytes). */
  readonly totalJsKb?: number;
  readonly totalHbcKb?: number;
  /** Max growth of any single module versus the base, in KiB. */
  readonly perModuleGrowthKb?: number;
  /** Module id prefixes excluded from the per-module growth check. */
  readonly ignore?: readonly string[];
}

export interface SizeDelta {
  readonly base: number;
  readonly head: number;
  readonly delta: number;
}

export interface ModuleDelta {
  readonly id: string;
  readonly baseBytes: number;
  readonly headBytes: number;
  readonly delta: number;
}

export interface BudgetViolation {
  readonly kind: 'totalJs' | 'totalHbc' | 'moduleGrowth';
  readonly module?: string;
  readonly limitKb: number;
  readonly actualKb: number;
}

export type BundleDiffStatus = 'ok' | 'over-budget' | 'not-comparable';

export interface BundleDiffResult {
  readonly status: BundleDiffStatus;
  /** Set when `status === 'not-comparable'`. */
  readonly reason?: string;
  readonly warnings: readonly string[];
  /** Budgets that could not be evaluated (e.g. a totalHbcKb budget with no bytecode measured). */
  readonly notChecked: readonly string[];
  readonly totals?: {
    readonly js: SizeDelta;
    /** `null` unless both snapshots measured bytecode. */
    readonly hbc: SizeDelta | null;
  };
  /** Largest first. */
  readonly added: readonly ModuleDelta[];
  readonly removed: readonly ModuleDelta[];
  readonly grown: readonly ModuleDelta[];
  readonly shrunk: readonly ModuleDelta[];
  readonly violations: readonly BudgetViolation[];
}
